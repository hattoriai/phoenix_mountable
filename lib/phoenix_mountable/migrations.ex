if Code.ensure_loaded?(Ecto.Migration) do
  defmodule PhoenixMountable.Migrations.Context do
    @moduledoc """
    What a library's migration version receives.

      * `:repo`, `:adapter` (`:postgres`, `:mysql` or `:sqlite`), `:prefix`
      * `:library` — the library's tracking name
      * `:version` — the version being run
      * `:install_options` — the options recorded at install time, with string
        keys and values (as stored), such as `%{"primary_key" => "binary_id"}`
      * `:backfills` — how backfills run in this migration: `:inline` or
        `:deferred` (see `PhoenixMountable.Backfill`)
      * `:opts` — the options given to `up/1` or `down/1`
    """

    @type t :: %__MODULE__{
            repo: module,
            adapter: :postgres | :mysql | :sqlite,
            prefix: String.t() | nil,
            library: String.t(),
            migrations: module,
            version: non_neg_integer,
            install_options: map,
            backfills: :inline | :deferred | nil,
            opts: keyword
          }

    defstruct [
      :repo,
      :adapter,
      :prefix,
      :library,
      :migrations,
      :version,
      :backfills,
      install_options: %{},
      opts: []
    ]
  end

  defmodule PhoenixMountable.Migrations do
    @moduledoc ~S"""
    Versioned migrations for a mountable library's tables in the host's database.

    The library writes the versions; the host owns one line per upgrade:

        # in the library
        defmodule MyLib.Migrations do
          use PhoenixMountable.Migrations,
            otp_app: :my_lib,
            versions: [MyLib.Migrations.V1, MyLib.Migrations.V2, MyLib.Migrations.V3]
        end

        # in the host, generated by `mix phoenix_mountable.gen.migration MyLib.Migrations`
        defmodule MyApp.Repo.Migrations.AddMyLib do
          use Ecto.Migration
          def up, do: MyLib.Migrations.up(version: 3)
          def down, do: MyLib.Migrations.down(to: 0)
        end

    Each version is a `PhoenixMountable.Migration` module. See the Migrations
    guide for the reasoning behind each rule.

    ## `use` options

      * `:otp_app` (required) — the library's application.
      * `:versions` (required) — the version modules in order, version 1 first;
        or a map of adapter (`:postgres`, `:mysql`, `:sqlite`) to such a list,
        when the SQL differs too much to share modules.
      * `:library` — the name the version is tracked under. Defaults to the
        `:otp_app`. Never change it after a release.
      * `:baseline` — a `PhoenixMountable.Migration` with `baseline: n`
        creating the whole schema at version `n`, run on fresh installs instead
        of versions 1 to `n`. `PhoenixMountable.Migrations.Test` checks that both
        paths give the same schema.
      * `:compatible_with` — the oldest schema version the library's current
        code runs against. Defaults to the latest version. Between it and the
        latest, the app works and logs that an upgrade is pending; below it,
        the library refuses to run and names the command that fixes it.
      * `:legacy` — a module with `detect(ctx) :: non_neg_integer | nil`,
        returning the version of a database migrated before the library used
        PhoenixMountable (from a table comment, or from the columns present).
      * `:install_options` — options the host chooses once, at install time,
        that later versions need, as a NimbleOptions schema. A `:primary_key`
        option (`type: {:in, [:id, :binary_id]}`) defaults to the repo's
        `:migration_primary_key` type.
      * `:lock_timeout` — how long a version waits for a table lock before
        failing, instead of queueing behind long transactions and blocking the
        app: `"5s"` by default on Postgres and MySQL; `false` to disable.
      * `:gen_task` — the Mix task hosts run to generate migrations, for
        messages. Defaults to `"phoenix_mountable.gen.migration <module>"`.

    ## Functions

    The module gets `up/1`, `down/1`, `migrated_version/1`, `latest_version/0`,
    `status/1`, `check/1`, `verify/1` and `run_backfills/1`.

    `up/1` options: `:version` (defaults to the latest, but hosts should pin
    it), `:prefix`, `:backfills` (`:inline` or `:deferred`, overriding each
    backfill's default) and the library's install options. `down/1` takes `:to`
    (the version to roll back to, default `0`) and `:prefix`.
    """

    @doc false
    defmacro __using__(opts) do
      quote bind_quoted: [opts: opts] do
        @phoenix_mountable_migrations PhoenixMountable.Migrations.__config__(__MODULE__, opts)

        @doc false
        def __phoenix_mountable_migrations__(key),
          do: Map.fetch!(@phoenix_mountable_migrations, key)

        @doc "Migrates the library's tables up. Call it from a host migration."
        def up(opts \\ []), do: PhoenixMountable.Migrations.Runner.up(__MODULE__, opts)

        @doc "Rolls the library's tables back to `:to` (default `0`). Call it from a host migration."
        def down(opts \\ []), do: PhoenixMountable.Migrations.Runner.down(__MODULE__, opts)

        @doc "The version the database is at (`0` when not installed)."
        def migrated_version(opts \\ []),
          do: PhoenixMountable.Migrations.Runner.migrated_version(__MODULE__, opts)

        @doc "The latest version of the library's schema."
        def latest_version, do: @phoenix_mountable_migrations.latest

        @doc "The version, compatibility and backfills of a database. Takes `:repo` and `:prefix`."
        def status(opts), do: PhoenixMountable.Migrations.Check.status(__MODULE__, opts)

        @doc "`:ok`, `{:pending, message}` or `{:outdated, message}`. Takes `:repo` and `:prefix`."
        def check(opts), do: PhoenixMountable.Migrations.Check.check(__MODULE__, opts)

        @doc "Checks the tables against the library's schema. Takes `:repo` and `:prefix`."
        def verify(opts), do: PhoenixMountable.Migrations.Check.verify(__MODULE__, opts)

        @doc "Runs deferred backfills to completion. Takes `:repo` and `:prefix`."
        def run_backfills(opts), do: PhoenixMountable.Backfill.Runner.run_all(__MODULE__, opts)
      end
    end

    @doc false
    def __config__(module, opts) do
      otp_app =
        Keyword.get(opts, :otp_app) ||
          raise ArgumentError, "use PhoenixMountable.Migrations needs :otp_app"

      versions =
        case Keyword.fetch(opts, :versions) do
          {:ok, list} when is_list(list) and list != [] ->
            %{default: list}

          {:ok, map} when is_map(map) and map_size(map) > 0 ->
            map

          _ ->
            raise ArgumentError,
                  "use PhoenixMountable.Migrations needs a non-empty :versions list"
        end

      lengths = versions |> Map.values() |> Enum.map(&length/1) |> Enum.uniq()

      if length(lengths) > 1 do
        raise ArgumentError,
              "every adapter must have the same number of versions, got: #{inspect(lengths)}"
      end

      [latest] = lengths

      install_options = Keyword.get(opts, :install_options, [])
      NimbleOptions.new!(install_options)

      lock_timeout = Keyword.get(opts, :lock_timeout, "5s")

      if lock_timeout not in [nil, false] and
           not Regex.match?(~r/\A\d+(ms|s|min)?\z/, to_string(lock_timeout)) do
        raise ArgumentError,
              ":lock_timeout must be like \"5s\", \"500ms\" or \"1min\", got: #{inspect(lock_timeout)}"
      end

      compatible_with = Keyword.get(opts, :compatible_with, latest)

      if compatible_with not in 0..latest//1 do
        raise ArgumentError,
              ":compatible_with must be between 0 and #{latest}, got: #{inspect(compatible_with)}"
      end

      %{
        otp_app: otp_app,
        library: to_string(Keyword.get(opts, :library, otp_app)),
        versions: versions,
        latest: latest,
        baseline: Keyword.get(opts, :baseline),
        compatible_with: compatible_with,
        legacy: Keyword.get(opts, :legacy),
        install_options: install_options,
        lock_timeout: lock_timeout,
        gen_task:
          Keyword.get(opts, :gen_task, "phoenix_mountable.gen.migration #{inspect(module)}")
      }
    end

    @doc """
    The version modules of a migrations module for an adapter.
    """
    @spec versions(module, atom) :: [module]
    def versions(migrations, adapter) do
      versions = migrations.__phoenix_mountable_migrations__(:versions)

      Map.get(versions, adapter) || Map.get(versions, :default) ||
        raise_no_versions(migrations, adapter)
    end

    defp raise_no_versions(migrations, adapter) do
      raise ArgumentError, "#{inspect(migrations)} has no versions for #{inspect(adapter)}"
    end

    @doc """
    Whether running versions `from + 1` to `to` needs the host migration to
    disable its DDL transaction and migration lock.
    """
    @spec no_transaction?(module, atom, non_neg_integer, non_neg_integer) :: boolean
    def no_transaction?(migrations, adapter, from, to) do
      migrations
      |> range_modules(adapter, from, to)
      |> Enum.any?(&(adapter in &1.__phoenix_mountable_migration__().no_transaction))
    end

    @doc false
    def range_modules(_migrations, _adapter, from, to) when to <= from, do: []

    def range_modules(migrations, adapter, from, to) do
      migrations |> versions(adapter) |> Enum.slice(from, to - from)
    end
  end

  defmodule PhoenixMountable.Migrations.Runner do
    @moduledoc false

    require Logger

    alias PhoenixMountable.Migrations
    alias PhoenixMountable.Migrations.{Context, SQL}

    @doc false
    def up(migrations, opts) do
      config = config(migrations)
      {repo, adapter, prefix} = env(opts)
      target = Keyword.get(opts, :version, config.latest)

      if target not in 0..config.latest//1 do
        raise ArgumentError,
              "#{inspect(migrations)} has versions 0 to #{config.latest}, got version: #{target}"
      end

      flush()
      SQL.ensure_tracking!(repo, adapter, prefix)

      ctx = %Context{
        repo: repo,
        adapter: adapter,
        prefix: prefix,
        library: config.library,
        migrations: migrations,
        backfills: Keyword.get(opts, :backfills),
        opts: opts
      }

      {current, install_options} = current(migrations, ctx, config, opts)
      ctx = %{ctx | install_options: install_options}

      if current >= target do
        :ok
      else
        check_transaction!(migrations, ctx, current, target)
        run_up(migrations, config, ctx, current, target)
      end
    end

    defp run_up(migrations, config, ctx, current, target) do
      start = System.monotonic_time()
      emit(:start, %{system_time: System.system_time()}, ctx, :up, current, target)

      with_lock_timeout(config, ctx, fn ->
        current =
          if config.baseline != nil and current == 0 and Keyword.get(ctx.opts, :baseline, true) do
            baseline = config.baseline
            baseline_version = baseline.__phoenix_mountable_migration__().baseline

            if target >= baseline_version do
              baseline.up(%{ctx | version: baseline_version})
              record!(ctx, baseline_version)
              baseline_version
            else
              0
            end
          else
            current
          end

        for {module, index} <-
              Enum.with_index(Migrations.range_modules(migrations, ctx.adapter, current, target)) do
          version = current + index + 1
          check_backfills!(ctx, module)
          module.up(%{ctx | version: version})
          record!(ctx, version)
        end
      end)

      emit(:stop, %{duration: System.monotonic_time() - start}, ctx, :up, current, target)
      :ok
    end

    @doc false
    def down(migrations, opts) do
      if Keyword.has_key?(opts, :version) do
        raise ArgumentError,
              "#{inspect(migrations)}.down/1 takes :to, the version to roll back to, " <>
                "not :version. For example: down(to: 2) undoes versions 3 and above."
      end

      config = config(migrations)
      {repo, adapter, prefix} = env(opts)
      target = Keyword.get(opts, :to, 0)

      flush()

      case SQL.fetch_row(repo, adapter, prefix, config.library) do
        {:ok, current, install_options} when current > target ->
          ctx = %Context{
            repo: repo,
            adapter: adapter,
            prefix: prefix,
            library: config.library,
            migrations: migrations,
            install_options: install_options,
            opts: opts
          }

          run_down(migrations, config, ctx, current, target)

        _ ->
          :ok
      end
    end

    defp run_down(migrations, config, ctx, current, target) do
      check_transaction!(migrations, ctx, target, current)

      # Newest first: version `current` is undone first.
      steps =
        migrations
        |> Migrations.range_modules(ctx.adapter, target, current)
        |> Enum.zip((target + 1)..current//1)
        |> Enum.reverse()

      for {module, version} <- steps,
          reason = module.__phoenix_mountable_migration__().irreversible do
        raise PhoenixMountable.MigrationError,
              "cannot roll #{config.library} back past version #{version} (#{inspect(module)}): #{reason}"
      end

      start = System.monotonic_time()
      emit(:start, %{system_time: System.system_time()}, ctx, :down, current, target)

      with_lock_timeout(config, ctx, fn ->
        for {module, version} <- steps do
          if Code.ensure_loaded?(module) and function_exported?(module, :down, 1),
            do: module.down(%{ctx | version: version})

          record!(ctx, version - 1)
        end
      end)

      emit(:stop, %{duration: System.monotonic_time() - start}, ctx, :down, current, target)
      :ok
    end

    @doc false
    def migrated_version(migrations, opts) do
      config = config(migrations)
      {repo, adapter, prefix} = env(opts)

      case SQL.fetch_row(repo, adapter, prefix, config.library) do
        {:ok, version, _} ->
          version

        :error ->
          ctx = %Context{
            repo: repo,
            adapter: adapter,
            prefix: prefix,
            library: config.library,
            migrations: migrations
          }

          legacy_version(config, ctx) || 0
      end
    end

    defp config(migrations) do
      %{
        latest: migrations.__phoenix_mountable_migrations__(:latest),
        library: migrations.__phoenix_mountable_migrations__(:library),
        baseline: migrations.__phoenix_mountable_migrations__(:baseline),
        legacy: migrations.__phoenix_mountable_migrations__(:legacy),
        install_options: migrations.__phoenix_mountable_migrations__(:install_options),
        lock_timeout: migrations.__phoenix_mountable_migrations__(:lock_timeout)
      }
    end

    # Inside a migration the repo and prefix come from the migrator; outside
    # (status checks, tests) from the options.
    defp env(opts) do
      repo = Keyword.get(opts, :repo) || migration_repo()
      adapter = SQL.adapter(repo)
      prefix = Keyword.get(opts, :prefix) || migration_prefix() || SQL.default_prefix(adapter)
      {repo, adapter, if(adapter == :sqlite, do: nil, else: prefix)}
    end

    defp migration_repo do
      if SQL.in_migration?() do
        Ecto.Migration.repo()
      else
        raise ArgumentError, "pass :repo when calling outside of a migration"
      end
    end

    defp migration_prefix do
      if SQL.in_migration?(), do: Ecto.Migration.prefix()
    end

    defp flush, do: SQL.flush()

    # The tracked version, else a legacy install's detected version, else 0 (a
    # fresh install, whose install options are resolved and stored now).
    defp current(migrations, ctx, config, opts) do
      case SQL.fetch_row(ctx.repo, ctx.adapter, ctx.prefix, config.library) do
        {:ok, version, stored} ->
          warn_ignored_install_options(migrations, stored, opts, config)
          {version, stored}

        :error ->
          options = resolve_install_options(migrations, config, ctx, opts)

          case legacy_version(config, %{ctx | install_options: options}) do
            nil ->
              {0, options}

            version ->
              Logger.info("#{config.library}: adopting an existing install at version #{version}")
              SQL.put_row!(ctx.repo, ctx.adapter, ctx.prefix, config.library, version, options)
              {version, options}
          end
      end
    end

    defp legacy_version(%{legacy: nil}, _ctx), do: nil
    defp legacy_version(%{legacy: legacy}, ctx), do: legacy.detect(ctx)

    defp resolve_install_options(migrations, config, ctx, opts) do
      schema =
        Enum.map(config.install_options, fn
          {:primary_key, spec} ->
            {:primary_key, Keyword.put(spec, :default, repo_primary_key(ctx.repo, spec))}

          other ->
            other
        end)

      given = Keyword.take(opts, Keyword.keys(schema))

      case NimbleOptions.validate(given, schema) do
        {:ok, options} ->
          Map.new(options, fn {key, value} -> {to_string(key), json_value(value)} end)

        {:error, error} ->
          raise ArgumentError,
                "invalid install options for #{inspect(migrations)}.up/1: #{error.message}"
      end
    end

    defp repo_primary_key(repo, spec) do
      case repo.config()[:migration_primary_key] do
        options when is_list(options) ->
          if options[:type] in [:binary_id, :uuid], do: :binary_id, else: spec[:default] || :id

        _ ->
          spec[:default] || :id
      end
    end

    defp json_value(value) when is_atom(value) and value not in [nil, true, false],
      do: Atom.to_string(value)

    defp json_value(value), do: value

    defp warn_ignored_install_options(migrations, stored, opts, config) do
      for {name, _spec} <- config.install_options,
          {:ok, value} <- [Keyword.fetch(opts, name)],
          Map.get(stored, to_string(name)) != json_value(value) do
        Logger.warning(
          "#{inspect(migrations)}: ignoring #{name}: #{inspect(value)}; it is an install option and the " <>
            "library was installed with #{inspect(Map.get(stored, to_string(name)))}"
        )
      end
    end

    # Concurrent index builds and SQLite table rebuilds cannot run in a
    # transaction. Fail before running anything, naming the attributes.
    defp check_transaction!(migrations, ctx, from, to) do
      if Migrations.no_transaction?(migrations, ctx.adapter, from, to) and
           ctx.repo.in_transaction?() do
        raise PhoenixMountable.MigrationError, """
        #{inspect(migrations)} versions #{from + 1} to #{to} include changes that cannot run inside a \
        transaction on #{ctx.adapter}, such as building an index concurrently. Add these lines to the \
        host migration that calls #{inspect(migrations)}:

            @disable_ddl_transaction true
            @disable_migration_lock true
        """
      end
    end

    defp check_backfills!(ctx, module) do
      required = module.__phoenix_mountable_migration__().requires_backfills

      if required != [] do
        done =
          ctx.repo
          |> SQL.backfill_rows(ctx.adapter, ctx.prefix, ctx.library)
          |> Enum.filter(&(&1.status == "done"))
          |> MapSet.new(& &1.name)

        for backfill <- required, not MapSet.member?(done, inspect(backfill)) do
          raise PhoenixMountable.MigrationError, """
          #{inspect(module)} needs the backfill #{inspect(backfill)} to have finished, and it has not. \
          Wait for it to finish (#{inspect(ctx.migrations)}.status/1 shows its progress) or run it with \
          `mix phoenix_mountable.backfill #{inspect(ctx.migrations)}`, then migrate again.
          """
        end
      end
    end

    defp record!(ctx, version) do
      flush()

      if version == 0 do
        SQL.delete_row!(ctx.repo, ctx.adapter, ctx.prefix, ctx.library)
      else
        SQL.put_row!(ctx.repo, ctx.adapter, ctx.prefix, ctx.library, version, ctx.install_options)
      end
    end

    defp with_lock_timeout(%{lock_timeout: timeout}, _ctx, fun) when timeout in [nil, false],
      do: fun.()

    defp with_lock_timeout(_config, %{adapter: :sqlite}, fun), do: fun.()

    defp with_lock_timeout(%{lock_timeout: timeout}, %{adapter: :postgres} = ctx, fun) do
      in_transaction? = ctx.repo.in_transaction?()

      SQL.query!(
        ctx.repo,
        "SET #{if in_transaction?, do: "LOCAL ", else: ""}lock_timeout = '#{timeout}'"
      )

      try do
        fun.()
      after
        flush()
        if not in_transaction?, do: SQL.query!(ctx.repo, "RESET lock_timeout")
      end
    end

    defp with_lock_timeout(%{lock_timeout: timeout}, %{adapter: :mysql} = ctx, fun) do
      seconds = seconds(timeout)
      [[previous]] = SQL.query!(ctx.repo, "SELECT @@SESSION.lock_wait_timeout").rows
      SQL.query!(ctx.repo, "SET SESSION lock_wait_timeout = #{seconds}")

      try do
        fun.()
      after
        flush()
        SQL.query!(ctx.repo, "SET SESSION lock_wait_timeout = #{previous}")
      end
    end

    defp seconds(timeout) do
      case Integer.parse(to_string(timeout)) do
        {n, "ms"} -> max(div(n, 1000), 1)
        {n, "min"} -> n * 60
        {n, _} -> n
        :error -> raise ArgumentError, "invalid :lock_timeout #{inspect(timeout)}"
      end
    end

    defp emit(event, measurements, ctx, direction, from, to) do
      PhoenixMountable.Telemetry.execute([:migration, event], measurements, %{
        library: ctx.library,
        direction: direction,
        from: from,
        to: to,
        repo: ctx.repo,
        prefix: ctx.prefix
      })
    end
  end
end

if Code.ensure_loaded?(Ecto.Migration) do
  defmodule PhoenixMountable.Migrations.Generator do
    @moduledoc """
    Writes the host's migration for installing or upgrading a library.

    Used by `mix phoenix_mountable.gen.migration` and by
    `PhoenixMountable.Igniter`. The version the host is at is read from its
    existing migrations: the highest `MyLib.Migrations.up(version: n)` among
    them. That works before the database is migrated (a new developer, CI),
    and keeps the host's history reproducible.
    """

    alias PhoenixMountable.Migrations

    @doc """
    The highest version pinned by `up(version: n)` calls to `migrations` in the
    `.exs` files of `dir`.

    Returns `{:ok, version}` (`0` when none), or `{:unpinned, files}` when a
    file calls `up/0` or `up/1` without a version, which cannot be read
    without the database.
    """
    @spec pinned_version(module, Path.t()) :: {:ok, non_neg_integer} | {:unpinned, [Path.t()]}
    def pinned_version(migrations, dir) do
      results =
        dir
        |> Path.join("*.exs")
        |> Path.wildcard()
        |> Enum.flat_map(fn file ->
          file |> File.read!() |> calls(migrations) |> Enum.map(&{file, &1})
        end)

      case for {file, :unpinned} <- results, do: file do
        [] ->
          {:ok, results |> Enum.map(fn {_file, version} -> version end) |> Enum.max(fn -> 0 end)}

        files ->
          {:unpinned, Enum.uniq(files)}
      end
    end

    @doc false
    def calls(source, migrations) do
      alias_parts = migrations |> Module.split() |> Enum.map(&String.to_atom/1)

      case Code.string_to_quoted(source) do
        {:ok, ast} ->
          {_, acc} =
            Macro.prewalk(ast, [], fn
              {{:., _, [{:__aliases__, _, ^alias_parts}, :up]}, _, args} = node, acc ->
                {node, [version_arg(args) | acc]}

              node, acc ->
                {node, acc}
            end)

          acc

        {:error, _} ->
          []
      end
    end

    defp version_arg([opts]) when is_list(opts) do
      case Keyword.get(opts, :version) do
        version when is_integer(version) -> version
        _ -> :unpinned
      end
    end

    defp version_arg(_), do: :unpinned

    @doc """
    The name and module body of the migration taking `migrations` from version
    `from` to `to` in `repo`.

    The body is what goes inside the migration module after `use
    Ecto.Migration`. The file itself is written by Ecto's
    `mix ecto.gen.migration` (see `write!/5`) or by Igniter's
    `Igniter.Libs.Ecto.gen_migration/4`, so its path, timestamp, module name
    and `use` line follow the host's Ecto conventions.
    """
    @spec render(module, module | {module, atom}, non_neg_integer, non_neg_integer) ::
            {String.t(), String.t()}
    def render(migrations, repo, from, to) do
      library = migrations.__phoenix_mountable_migrations__(:library)

      # `{repo, adapter}` when the repo cannot be loaded (an installer running
      # before the host compiles).
      adapter =
        case repo do
          {_repo, adapter} -> adapter
          repo -> PhoenixMountable.Migrations.SQL.adapter(repo)
        end

      name = if from == 0, do: "add_#{library}", else: "upgrade_#{library}_to_v#{to}"
      infos = infos(migrations, adapter, from, to)

      lines =
        for {module, version} <- infos do
          info = module.__phoenix_mountable_migration__()

          "#   v#{version} (#{info.safety})#{if info.description, do: " " <> info.description, else: ""}"
        end

      notes = Enum.map(notes(migrations, infos, adapter), &("#\n" <> comment(&1)))

      attributes =
        if Migrations.no_transaction?(migrations, adapter, from, to) do
          [
            "",
            "# Some of these versions cannot run in a transaction on #{adapter}",
            "# (for example, a concurrent index build).",
            "@disable_ddl_transaction true",
            "@disable_migration_lock true"
          ]
        else
          []
        end

      body =
        Enum.join(
          [
            "# #{library}: version #{from} to #{to}, generated by mix " <>
              migrations.__phoenix_mountable_migrations__(:gen_task),
            "#"
          ] ++
            lines ++
            notes ++
            attributes ++
            [
              "",
              "def up do",
              "  #{inspect(migrations)}.up(version: #{to})",
              "end",
              "",
              "def down do",
              "  #{inspect(migrations)}.down(to: #{from})",
              "end"
            ],
          "\n"
        )

      {name, body}
    end

    @doc """
    Writes the migration with `mix ecto.gen.migration`, then fills in its body.

    `args` are passed to Ecto's task: `-r`/`--repo` and `--migrations-path`.
    Returns the file written.
    """
    @spec write!(module, module, non_neg_integer, non_neg_integer, [String.t()]) :: Path.t()
    def write!(migrations, repo, from, to, args \\ []) do
      {name, body} = render(migrations, repo, from, to)
      {opts, _, _} = OptionParser.parse(args, strict: [migrations_path: :string])
      path_args = if path = opts[:migrations_path], do: ["--migrations-path", path], else: []
      [file] = Mix.Tasks.Ecto.Gen.Migration.run([name, "--repo", inspect(repo) | path_args])

      # Ecto's template ends with an empty `def change`; put the body there.
      generated = File.read!(file)
      [head | _] = String.split(generated, ~r/\n\s*def change do/, parts: 2)
      File.write!(file, head <> "\n\n" <> indent(body) <> "\nend\n")
      file
    end

    defp indent(body) do
      body
      |> String.split("\n")
      |> Enum.map_join("\n", fn
        "" -> ""
        line -> "  " <> line
      end)
    end

    @doc false
    def infos(migrations, adapter, from, to) do
      Enum.zip(Migrations.range_modules(migrations, adapter, from, to), (from + 1)..to//1)
    end

    @doc false
    def notes(migrations, infos, _adapter) do
      contract =
        for {module, version} <- infos,
            module.__phoenix_mountable_migration__().safety == :contract do
          "Version #{version} is a contract change: it breaks code that still reads the previous schema. " <>
            "Deploy the new version of the library before running this migration, or run it after the " <>
            "deploy completes on every node."
        end

      irreversible =
        for {module, version} <- infos,
            reason = module.__phoenix_mountable_migration__().irreversible do
          "Version #{version} cannot be rolled back: #{reason}"
        end

      deferred =
        if Enum.any?(infos, fn {module, _} -> uses_backfill?(module) end) do
          [
            "These versions include backfills. Deferred ones run in the app: start " <>
              "{PhoenixMountable.Backfill.Runner, migrations: #{inspect(migrations)}, repo: YourRepo} " <>
              "or run `mix phoenix_mountable.backfill #{inspect(migrations)}`."
          ]
        else
          []
        end

      contract ++ irreversible ++ deferred
    end

    defp uses_backfill?(module), do: module.__phoenix_mountable_migration__().backfills?

    defp comment(text) do
      text
      |> String.split(" ")
      |> Enum.chunk_while(
        [],
        fn word, acc ->
          line = Enum.join(Enum.reverse([word | acc]), " ")

          if String.length(line) > 72 and acc != [],
            do: {:cont, Enum.reverse(acc), [word]},
            else: {:cont, [word | acc]}
        end,
        fn acc -> {:cont, Enum.reverse(acc), []} end
      )
      |> Enum.map_join("\n", &"# #{Enum.join(&1, " ")}")
    end
  end
end
